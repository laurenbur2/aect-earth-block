#!/usr/bin/env python3
"""Make the old-site redirects in site/_redirects work on GitHub Pages, which can't do server redirects.

For each exact rule (/faqs -> /learn) it writes site/faqs/index.html, a tiny page that forwards instantly
(meta refresh + canonical, which Google treats like a permanent redirect). Wildcard rules (/aect-blog/*)
go into site/404.html, which forwards matching paths and shows "page not found" for everything else.
Cloudflare still reads _redirects directly. After editing _redirects, run from the repo root:
    python3 tools/build_redirect_pages.py
"""
import html
import json
import pathlib
import shutil

SITE = pathlib.Path(__file__).resolve().parent.parent / "site"
MARK = "<!-- generated by tools/build_redirect_pages.py -->"


def rules():
    for line in (SITE / "_redirects").read_text().splitlines():
        parts = line.split()
        if len(parts) >= 2 and not line.lstrip().startswith("#"):
            yield parts[0], parts[1]


def stub(src, dest):
    depth = src.strip("/").count("/") + 1
    rel = "../" * depth + dest.lstrip("/")
    canon = "https://aectearthblock.com" + dest
    return f"""<!doctype html>
{MARK}
<html lang="en"><head><meta charset="utf-8">
<title>Moved</title>
<link rel="canonical" href="{html.escape(canon)}">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url={html.escape(rel)}">
<script>location.replace({json.dumps(rel)} + (location.hash || ""));</script>
</head><body><p>This page moved: <a href="{html.escape(rel)}">continue</a>.</p></body></html>
"""


def main():
    # Remove stubs from a previous run (only folders this script made).
    for f in SITE.rglob("index.html"):
        if MARK in f.read_text(errors="ignore"):
            f.unlink()
            d = f.parent
            while d != SITE and not any(d.iterdir()):
                d.rmdir()
                d = d.parent
    exact, wild = [], []
    for src, dest in rules():
        if src.endswith("/*"):
            wild.append((src[:-1], dest))
            continue
        if (SITE / (src.strip("/") + ".html")).exists():
            continue  # same address on the new site
        out = SITE / src.strip("/") / "index.html"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(stub(src, dest))
        exact.append(src)
    (SITE / "404.html").write_text(f"""<!doctype html>
{MARK}
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Page not found | AECT Earth Block</title>
<meta name="robots" content="noindex">
<script>
  // Old-site addresses with a wildcard rule in _redirects (GitHub Pages serves this page for any missing path).
  (function () {{
    var base = location.hostname.endsWith("github.io") ? "/" + location.pathname.split("/")[1] + "/" : "/";
    var path = "/" + location.pathname.slice(base.length);
    var rules = {json.dumps(wild)};
    for (var i = 0; i < rules.length; i++) {{
      if (path.indexOf(rules[i][0]) === 0) {{ location.replace(base + rules[i][1].replace(/^\\//, "")); return; }}
    }}
    document.documentElement.dataset.base = base;
  }})();
</script>
<style>body{{font:16px/1.5 system-ui,sans-serif;background:#f4efe6;color:#2b2f36;display:grid;place-items:center;min-height:100vh;margin:0;padding:16px;text-align:center}}a{{color:#435068;font-weight:600}}</style>
</head><body><div><h1>Page not found</h1><p>That page isn't here anymore.</p>
<p><a href="/" onclick="this.href=document.documentElement.dataset.base||'/'">Go to the AECT home page</a></p></div></body></html>
""")
    print(f"{len(exact)} forwarding pages, {len(wild)} wildcard rules in 404.html")


if __name__ == "__main__":
    main()
